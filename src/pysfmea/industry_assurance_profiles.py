from __future__ import annotations

from typing import Any


def _objective(
    identifier: str, title: str, locator: str, *evidence: str
) -> dict[str, Any]:
    return {
        "id": identifier,
        "title": title,
        "reference_locator": locator,
        "expected_evidence": list(evidence),
    }


def _profile(
    identifier: str,
    title: str,
    publisher: str,
    edition: str,
    status: str,
    url: str,
    access: str,
    scope: str,
    objectives: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "id": identifier,
        "title": title,
        "publisher": publisher,
        "edition": edition,
        "status": status,
        "reference_url": url,
        "access": access,
        "scope": scope,
        "objectives": objectives,
    }


